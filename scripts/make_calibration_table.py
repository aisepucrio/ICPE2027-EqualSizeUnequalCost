#!/usr/bin/env python3
"""Cost-to-size ratio r = %cost / %n per strategy and corpus (Section 4.2 of the paper).

For every corpus, r is computed per (scope, strategy) in the strategy summary, and the table
reports its median over scopes with the 10th and 90th percentiles. The x264 corpus is taken at
the t2 budget, as in the paper; diagnostic oracle strategies are excluded. The last row gives
the median over all strategies of the corpus.

Writes artifacts/calibration/calibration_ratio_table.{csv,md}.

Usage: python scripts/make_calibration_table.py [--artifacts DIR] [--out DIR]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
CORPORA = {
    "Kaltenecker": "fse_posterior_fse_artifact_final_t2",
    "x264": "fse_posterior_x264_icpe_final",
    "Energy": "fse_posterior_energy_final",
    "Workload": "fse_posterior_workload_final",
    "Linux": "fse_posterior_linux_all_full",
    "LCBench": "fse_posterior_lcbench_no_oracles_final",
}
STRATEGIES = {
    "random": "Uniform random",
    "SRSSampling": "SRS",
    "divDistBased": "Distance-based",
    "distBased": "Distance-based (plain)",
    "henard": "Randomized solver",
    "solverBased": "Solver-based",
    "twise": "2-wise",
    "diversity": "Diversity",
    "balanced": "Balanced",
    "pairwise": "Pairwise",
    "pilotCost": "pilotCost",
    "coverage": "Coverage",
    "uncertainty": "Uncertainty",
}
ORACLES = {"cheapOracle", "expensiveOracle"}


def summary(artifacts: Path, corpus: str) -> pd.DataFrame:
    s = pd.read_csv(artifacts / CORPORA[corpus] / "posterior_strategy_summary.csv")
    s = s[~s.strategy.isin(ORACLES)]
    if corpus == "x264":
        s = s[s.level == "t2"]
    return s


def cell(r: pd.Series) -> str:
    return f"{r.median():.2f} ({r.quantile(0.1):.2f}-{r.quantile(0.9):.2f})"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--artifacts", type=Path, default=REPO / "artifacts")
    parser.add_argument("--out", type=Path, default=REPO / "artifacts" / "calibration")
    args = parser.parse_args()

    data = {c: summary(args.artifacts, c) for c in CORPORA}
    rows, long = [], []
    for key, label in STRATEGIES.items():
        row = {"strategy": label}
        for corpus, s in data.items():
            r = s[s.strategy == key].median_calibration_ratio
            row[corpus] = cell(r) if len(r) else "--"
            if len(r):
                long.append({"corpus": corpus, "strategy": label, "scopes": len(r), "median": r.median(),
                             "p10": r.quantile(0.1), "p90": r.quantile(0.9)})
        rows.append(row)
    rows.append({"strategy": "All strategies", **{c: cell(s.median_calibration_ratio) for c, s in data.items()}})
    table = pd.DataFrame(rows)

    args.out.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(long).to_csv(args.out / "calibration_ratio_table.csv", index=False, float_format="%.4f")
    header = "| Strategy | " + " | ".join(CORPORA) + " |"
    lines = [
        "# Cost-to-size ratio per strategy and corpus",
        "",
        "Median of r = %cost / %n over scopes, with the 10th to 90th percentile in parentheses",
        "(x264 at t2). A ratio of 1 means that a sample costs exactly what its size suggests.",
        "Generated by `scripts/make_calibration_table.py`.",
        "",
        header,
        "|" + "---|" * (len(CORPORA) + 1),
    ]
    lines += ["| " + " | ".join(str(v) for v in r.values) + " |" for _, r in table.iterrows()]
    (args.out / "calibration_ratio_table.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[6:]))


if __name__ == "__main__":
    main()
